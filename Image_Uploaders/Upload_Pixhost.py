"""
Upload_Pixhost.py - Pixhost (https://pixhost.to) anonymous image uploader for File_Prepare_HF.

API reference: https://pixhost.to/api/index.html  (Pixhost API v2, no API key / account required)

WHAT THIS MODULE DOES
---------------------
* Uploads one image per call to Pixhost, always flagged as adult content (`content_type=1`, NSFW).
  `content_type` is a REQUIRED field of the Pixhost upload endpoint (0 = safe, 1 = NSFW), so it is
  relevant for API uploads and is always sent.
* Always sends `include_manage_url=1`. Pixhost is anonymous, so the returned `manage_url` is the ONLY
  way to delete/rename an upload later (it cannot be recovered afterwards). It is saved in two places:
    1. `<base_name>_pixhost.txt` next to the image (same JSON layout as the other hosts' result files,
       and it is deleted/regenerated by main.py at the start of every run, like the other hosts' files).
    2. `Resources/pixhost_manage_links.jsonl`: an APPEND-ONLY log that is never deleted by the
       application (the Resources folder is created if it does not exist). This is the permanent record of every delete link. KEEP THIS FILE PRIVATE
       (it is already listed in .gitignore) - anyone holding a manage_url can delete the image.
* Provides `pixhost_delete_image()` to delete an upload using its manage_url (e.g. an invalid image).

HOW TO USE (inside the application)
-----------------------------------
main.py / Generate_Video_Preview.py call:

    ok = await pixhost_upload_single_image(filepath, new_filename_base_name, mode)

  filepath               - full path of the image to upload
  new_filename_base_name - base name used for the result file name and the result key
  mode                   - label such as "cover", "thumbnails", "Preview WebP", "Preview Sheet WebP"
  returns True on success, False on failure (same contract as hamster_upload_single_image).

Enable it in Configs/Config.json with: pixhost_upload_cover, pixhost_upload_thumbnails,
pixhost_upload_previews.

HOW TO USE (command line, from the project root)
------------------------------------------------
    python Image_Uploaders/Upload_Pixhost.py list                 # uploads that were not deleted yet
    python Image_Uploaders/Upload_Pixhost.py delete <manage_url>  # delete an upload by its manage_url

Pixhost limits: JPEG / PNG / GIF / WebP / AVIF only, 10 MB maximum per image.
"""
import asyncio
import json
import mimetypes
import os
import re
import sys
from datetime import datetime, timezone
from urllib.parse import urlparse

import httpx
from loguru import logger

# ----------------------------------------------------------------------------------------------
# Configuration constants
# ----------------------------------------------------------------------------------------------
# Pixhost serves the same API on several domains; use the one whose links you want in the response.
# Available: https://api.pixhost.to, https://api.pixhost.cc, https://api.pixho.st
PIXHOST_API_BASE = "https://api.pixhost.to"

# 0 = safe for work, 1 = NSFW. All uploads from this project are adult content.
PIXHOST_CONTENT_TYPE = 1

# Pixhost per-image limits and supported formats (from the API documentation).
PIXHOST_MAX_FILE_BYTES = 10 * 1024 * 1024
PIXHOST_SUPPORTED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".gif", ".webp", ".avif"}

# Timeout for upload requests (seconds). Increase if large/slow uploads keep timing out.
PIXHOST_UPLOAD_TIMEOUT = httpx.Timeout(connect=10.0, read=120.0, write=120.0, pool=10.0)

# Permanent, append-only log of every upload (including its private manage_url) and every deletion.
PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PIXHOST_MANAGE_LOG = os.path.join(PROJECT_ROOT, "Resources", "pixhost_manage_links.jsonl")

# Meaning of the API's error status codes (note: 414-417 are legacy API-specific meanings).
_PIXHOST_ERRORS = {
    400: "invalid request / missing file",
    413: "file exceeds the size limit",
    414: "unsupported image format",
    422: "upload rejected",
    429: "rate limited",
    500: "Pixhost internal server error",
}


# ----------------------------------------------------------------------------------------------
# Internal helpers
# ----------------------------------------------------------------------------------------------
def _make_client():
    """Create the HTTP client. Kept as a function so tests can swap in a mock transport."""
    return httpx.AsyncClient(timeout=PIXHOST_UPLOAD_TIMEOUT)


def _utc_now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def derive_direct_image_url(thumbnail_url):
    """
    Pixhost's API returns only the viewer page (`show_url`) and the thumbnail (`th_url`), not a direct
    image link. This derives the direct link from the thumbnail URL:
        https://t1.pixhost.to/thumbs/8582/563_image.jpg -> https://img1.pixhost.to/images/8582/563_image.jpg
    NOTE: this URL pattern is NOT part of the documented API. It is isolated here so it can be fixed in
    one place if Pixhost changes it. Returns None when the thumbnail URL has an unexpected shape.
    """
    if not thumbnail_url:
        return None
    match = re.match(r"^(https?://)t(\d+)\.([^/]+)/thumbs/(.+)$", thumbnail_url)
    if not match:
        return None
    scheme, server, host, path = match.groups()
    return f"{scheme}img{server}.{host}/images/{path}"


def _append_manage_log(record):
    """Append one JSON line to the permanent manage-links log. Never raises; returns True on success."""
    try:
        os.makedirs(os.path.dirname(PIXHOST_MANAGE_LOG), exist_ok=True)
        with open(PIXHOST_MANAGE_LOG, "a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")
        return True
    except Exception as e:
        logger.error(f"Failed to write Pixhost manage-links log ({PIXHOST_MANAGE_LOG}): {e}")
        return False


def _append_result_file(txt_filepath, key, result):
    """Add `result` under `key` in the per-image JSON result file (created if missing)."""
    data = {}
    if os.path.exists(txt_filepath):
        try:
            with open(txt_filepath, "r", encoding="utf-8") as f:
                data = json.load(f)
        except json.JSONDecodeError:
            data = {}
    data.setdefault(key, []).append(result)
    with open(txt_filepath, "w", encoding="utf-8") as f:
        f.write(json.dumps(data, indent=2))


def _manage_token(manage_url):
    """The management token is the last path segment of manage_url."""
    path = urlparse(manage_url).path.strip("/")
    return path.split("/")[-1] if path else ""


# ----------------------------------------------------------------------------------------------
# Public API
# ----------------------------------------------------------------------------------------------
async def upload_to_pixhost(filepath):
    """
    Upload one image to Pixhost (adult content, with management URL requested).
    Returns the Pixhost response dict (name, show_url, th_url, thumb_width, thumb_height, manage_url)
    or None on failure. Does not write any files; see pixhost_upload_single_image for that.
    """
    if not os.path.isfile(filepath):
        logger.error(f"File not found: {filepath}")
        return None

    extension = os.path.splitext(filepath)[1].lower()
    if extension not in PIXHOST_SUPPORTED_EXTENSIONS:
        logger.error(f"Pixhost does not support '{extension}' files: {filepath}")
        return None

    size = os.path.getsize(filepath)
    if size > PIXHOST_MAX_FILE_BYTES:
        logger.error(f"File is {size / 1024 / 1024:.1f} MB, above Pixhost's 10 MB limit: {filepath}")
        return None

    mime_type = mimetypes.guess_type(filepath)[0] or "application/octet-stream"
    with open(filepath, "rb") as f:
        file_bytes = f.read()

    try:
        async with _make_client() as client:
            response = await client.post(
                f"{PIXHOST_API_BASE}/images",
                headers={"Accept": "application/json"},
                files={"img": (os.path.basename(filepath), file_bytes, mime_type)},
                data={"content_type": str(PIXHOST_CONTENT_TYPE), "include_manage_url": "1"},
            )
    except httpx.HTTPError as e:
        logger.error(f"Pixhost request failed: {type(e).__name__}: {e}")
        return None

    if response.status_code != 200:
        reason = _PIXHOST_ERRORS.get(response.status_code, "unexpected error")
        logger.error(f"Pixhost upload failed (HTTP {response.status_code}: {reason}): {filepath}")
        return None

    try:
        resp_json = response.json()
    except ValueError:
        logger.error("Pixhost returned an invalid JSON response.")
        return None

    if not resp_json.get("show_url"):
        logger.error("Pixhost response has no 'show_url'; upload result unknown.")
        return None
    return resp_json


async def pixhost_upload_single_image(filepath, new_filename_base_name, mode):
    """
    Upload one image and persist its links. Returns True on success, False on failure.
    See the module docstring for the arguments and for where the delete link is stored.
    """
    resp = await upload_to_pixhost(filepath)
    if not resp:
        return False

    show_url = resp.get("show_url")
    thumbnail_url = resp.get("th_url")
    manage_url = resp.get("manage_url")
    key = f"{new_filename_base_name} - {mode}"

    # 1) Permanent delete-link record FIRST, so the link survives even if a later step fails.
    if manage_url:
        _append_manage_log({
            "event": "upload",
            "timestamp": _utc_now(),
            "local_file": os.path.abspath(filepath),
            "key": key,
            "show_url": show_url,
            "manage_url": manage_url,
        })
    else:
        logger.warning(f"Pixhost returned no manage_url for {filepath}; this upload cannot be deleted later.")

    # 2) Per-image result file (same layout as the other hosts, read when building the template).
    result = {
        "image_url": derive_direct_image_url(thumbnail_url),
        "show_url": show_url,
        "thumbnail_url": thumbnail_url,
        "manage_url": manage_url,
    }
    txt_filepath = os.path.join(os.path.dirname(filepath), f"{new_filename_base_name}_pixhost.txt")
    try:
        _append_result_file(txt_filepath, key, result)
    except Exception as e:
        logger.error(f"Failed to write Pixhost result file {txt_filepath}: {e}")
        return False

    logger.success(f"Pixhost upload successful: {os.path.basename(filepath)}")
    return True


async def pixhost_delete_image(manage_url):
    """
    Delete an upload (or gallery) using the manage_url saved at upload time.
    Returns True when Pixhost confirms the deletion (or reports it as already gone).
    """
    token = _manage_token(manage_url)
    if not token:
        logger.error("Invalid manage_url: no management token found.")
        return False

    try:
        async with _make_client() as client:
            response = await client.post(
                f"{PIXHOST_API_BASE}/management/{token}/delete",
                headers={"Accept": "application/json"},
            )
    except httpx.HTTPError as e:
        logger.error(f"Pixhost delete request failed: {type(e).__name__}: {e}")
        return False

    if response.status_code == 410:
        logger.warning("Pixhost reports this content was already deleted (or the token was revoked).")
    elif response.status_code == 404:
        logger.error("Pixhost does not know this management token.")
        return False
    elif response.status_code != 200:
        logger.error(f"Pixhost delete failed (HTTP {response.status_code}).")
        return False

    _append_manage_log({"event": "delete", "timestamp": _utc_now(), "manage_url": manage_url})
    logger.success("Pixhost image deleted.")
    return True


def pixhost_pending_uploads():
    """Return the logged uploads that have no matching 'delete' record yet (oldest first)."""
    if not os.path.isfile(PIXHOST_MANAGE_LOG):
        return []
    uploads, deleted = [], set()
    with open(PIXHOST_MANAGE_LOG, "r", encoding="utf-8") as f:
        for line in f:
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            if record.get("event") == "upload":
                uploads.append(record)
            elif record.get("event") == "delete":
                deleted.add(record.get("manage_url"))
    return [u for u in uploads if u.get("manage_url") not in deleted]


# ----------------------------------------------------------------------------------------------
# Command line helper (run from the project root): list / delete
# ----------------------------------------------------------------------------------------------
if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) == 1 and args[0] == "list":
        for rec in pixhost_pending_uploads():
            print(f"{rec['timestamp']}  {rec['key']}\n  view:   {rec['show_url']}\n  delete: {rec['manage_url']}")
    elif len(args) == 2 and args[0] == "delete":
        sys.exit(0 if asyncio.run(pixhost_delete_image(args[1])) else 1)
    else:
        print("Usage:\n  python Image_Uploaders/Upload_Pixhost.py list\n  python Image_Uploaders/Upload_Pixhost.py delete <manage_url>")
        sys.exit(2)
